  private async fetchResponses() {
    if (this.isSupabaseLive && this.supabase) {
      try {
        const { data, error } = await this.supabase
          .from('responses')
          .select('*')
          .order('created_at', { ascending: false });

        if (!error && data) {
          this.allResponses = data;
        } else {
          const stored = localStorage.getItem(STORAGE_RESPONSES_KEY);
          this.allResponses = stored ? JSON.parse(stored) : DEFAULT_SAMPLE_RESPONSES;
        }
      } catch (e) {
        console.warn('Error fetching responses from Supabase:', e);
        const stored = localStorage.getItem(STORAGE_RESPONSES_KEY);
        this.allResponses = stored ? JSON.parse(stored) : DEFAULT_SAMPLE_RESPONSES;
      }
    } else {
      const stored = localStorage.getItem(STORAGE_RESPONSES_KEY);
      this.allResponses = stored ? JSON.parse(stored) : DEFAULT_SAMPLE_RESPONSES;
    }
  }

  // 4. Save Response Data
  private async submitUserResponses(): Promise<boolean> {
    if (!this.userInfo.gender || !this.userInfo.age || !this.userInfo.userGroup) {
      alert('참여자 정보가 누락되었습니다.');
      return false;
    }

    const newRecord: ResponseRecord = {
      gender: this.userInfo.gender,
      age: Number(this.userInfo.age),
      user_group: this.userInfo.userGroup,
      q1_choice: this.userResponses.q1_choice || 'A',
      q1_reason: this.userResponses.q1_reason || '',
      q2_choice: this.userResponses.q2_choice || 'A',
      q2_reason: this.userResponses.q2_reason || '',
      q3_choice: this.userResponses.q3_choice || 'A',
      q3_reason: this.userResponses.q3_reason || '',
      created_at: new Date().toISOString()
    };

    if (this.isSupabaseLive && this.supabase) {
      try {
        const { error } = await this.supabase.from('responses').insert([newRecord]);
        if (error) {
          console.error('Supabase insert error:', error);
          this.saveToLocalStorage(newRecord);
        }
      } catch (err) {
        console.error('Supabase save exception:', err);
        this.saveToLocalStorage(newRecord);
      }
    } else {
      this.saveToLocalStorage(newRecord);
    }

    await this.fetchResponses();
    return true;
  }

  private saveToLocalStorage(record: ResponseRecord) {
    const current = JSON.parse(localStorage.getItem(STORAGE_RESPONSES_KEY) || '[]');
    record.id = Date.now();
    current.unshift(record);
    localStorage.setItem(STORAGE_RESPONSES_KEY, JSON.stringify(current));
  }

