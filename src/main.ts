  // 1. Initialize Supabase Client with graceful fallback
  private initSupabaseClient() {
    const metaEnv = (import.meta as any).env || {};
    const envUrl = (metaEnv.VITE_SUPABASE_URL as string) || localStorage.getItem(CUSTOM_URL_KEY) || '';
    const envKey = (metaEnv.VITE_SUPABASE_ANON_KEY as string) || localStorage.getItem(CUSTOM_KEY_KEY) || '';

    const isValidUrl = envUrl && envUrl.startsWith('http') && !envUrl.includes('your-supabase-project');
    const isValidKey = envKey && envKey.length > 20 && !envKey.includes('your-supabase-anon-key');

    if (isValidUrl && isValidKey) {
      try {
        this.supabase = createClient(envUrl, envKey);
        this.isSupabaseLive = true;
      } catch (err) {
        console.warn('Supabase Client Init Failed, using Local Storage fallback.', err);
        this.isSupabaseLive = false;
      }
    } else {
      this.isSupabaseLive = false;
    }

    this.updateDBStatusBadge();
  }

  private updateDBStatusBadge() {
    const badgeEl = document.getElementById('db-status-badge');
    const textEl = document.getElementById('db-status-text');
    if (!badgeEl || !textEl) return;

    if (this.isSupabaseLive) {
      badgeEl.className = 'inline-flex items-center space-x-1.5 px-2.5 py-1 rounded-full text-xs font-semibold bg-emerald-50 text-emerald-700 border border-emerald-200 cursor-pointer shadow-2xs';
      badgeEl.innerHTML = '<span class="w-2 h-2 rounded-full bg-emerald-500 animate-pulse"></span><span>Supabase 연동됨</span>';
    } else {
      badgeEl.className = 'inline-flex items-center space-x-1.5 px-2.5 py-1 rounded-full text-xs font-semibold bg-amber-50 text-amber-700 border border-amber-200 cursor-pointer shadow-2xs';
      badgeEl.innerHTML = '<span class="w-2 h-2 rounded-full bg-amber-500 animate-pulse"></span><span>로컬 시뮬레이션 모드</span>';
    }
  }

