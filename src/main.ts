  private exportReportCSV() {
    if (this.allResponses.length === 0) {
      alert('다운로드할 응답 데이터가 없습니다.');
      return;
    }
    const headers = ['ID', '성별', '연령', '소속그룹', 'Q1선택', 'Q1이유', 'Q2선택', 'Q2이유', 'Q3선택', 'Q3이유', '작성일시'];
    const rows = this.allResponses.map((r, i) => [
      r.id || i + 1,
      r.gender,
      r.age,
      r.user_group,
      `"${r.q1_choice}"`,
      `"${(r.q1_reason || '').replace(/"/g, '""')}"`,
      `"${r.q2_choice}"`,
      `"${(r.q2_reason || '').replace(/"/g, '""')}"`,
      `"${r.q3_choice}"`,
      `"${(r.q3_reason || '').replace(/"/g, '""')}"`,
      r.created_at || ''
    ]);
    const csvContent = '\uFEFF' + [headers.join(','), ...rows.map(row => row.join(','))].join('\n');
    const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.setAttribute('download', `AI_Ethics_Report_${new Date().toISOString().slice(0, 10)}.csv`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  }

