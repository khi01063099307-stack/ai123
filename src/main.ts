  // Filter Helper
  private getFilteredResponses(): ResponseRecord[] {
    return this.allResponses.filter(r => {
      // Gender Filter
      if (this.filterState.gender !== 'all' && r.gender !== this.filterState.gender) {
        return false;
      }

      // User Group Filter
      if (this.filterState.userGroup !== 'all' && r.user_group !== this.filterState.userGroup) {
        return false;
      }

      // Age Group Filter
      if (this.filterState.ageGroup !== 'all') {
        const age = r.age;
        if (this.filterState.ageGroup === '10under' && age >= 10) return false;
        if (this.filterState.ageGroup === '10s' && (age < 10 || age >= 20)) return false;
        if (this.filterState.ageGroup === '20s' && (age < 20 || age >= 30)) return false;
        if (this.filterState.ageGroup === '30plus' && age < 30) return false;
      }

      return true;
    });
  }

  // Destroy previous Chart.js instances to avoid canvas reuse bugs
  private destroyActiveCharts() {
    this.activeCharts.forEach(chart => chart.destroy());
    this.activeCharts.clear();
  }

  // 6. Chart.js Instantiation
  private renderStatsCharts() {
    const filtered = this.getFilteredResponses();

    [1, 2, 3].forEach(qNum => {
      const canvasId = `chart-q${qNum}`;
      const canvas = document.getElementById(canvasId) as HTMLCanvasElement;
      if (!canvas) return;

      const qChoiceKey = `q${qNum}_choice` as keyof ResponseRecord;
      const countA = filtered.filter(r => r[qChoiceKey] === 'A').length;
      const countB = filtered.filter(r => r[qChoiceKey] === 'B').length;

      const chart = new Chart(canvas, {
        type: 'doughnut',
        data: {
          labels: ['옵션 A', '옵션 B'],
          datasets: [
            {
              data: [countA, countB],
              backgroundColor: ['#4f46e5', '#0284c7'],
              hoverBackgroundColor: ['#4338ca', '#0369a1'],
              borderWidth: 2,
              borderColor: '#ffffff'
            }
          ]
        },
        options: {
          responsive: true,
          maintainAspectRatio: false,
          plugins: {
            legend: {
              display: false
            },
            tooltip: {
              callbacks: {
                label: (context) => {
                  const label = context.label || '';
                  const value = context.parsed || 0;
                  const total = countA + countB;
                  const pct = total > 0 ? Math.round((value / total) * 100) : 0;
                  return ` ${label}: ${value}명 (${pct}%)`;
                }
              }
            }
          },
          cutout: '68%'
        }
      });

      this.activeCharts.set(canvasId, chart);
    });
  }
