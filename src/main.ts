  private attachDilemmaEvents(index: number) {
    const questionNum = index + 1;
    const currentChoiceKey = `q${questionNum}_choice` as 'q1_choice' | 'q2_choice' | 'q3_choice';
    const currentReasonKey = `q${questionNum}_reason` as 'q1_reason' | 'q2_reason' | 'q3_reason';

    // Option Buttons Click
    document.querySelectorAll('.option-btn').forEach(btn => {
      btn.addEventListener('click', (e) => {
        const target = e.currentTarget as HTMLButtonElement;
        const choice = target.getAttribute('data-choice') as 'A' | 'B';
        
        this.userResponses[currentChoiceKey] = choice;
        this.renderDilemmaScreenRebind(index);
      });
    });

    // Reason Textarea Input
    const reasonTextarea = document.getElementById('input-dilemma-reason') as HTMLTextAreaElement;
    reasonTextarea?.addEventListener('input', (e) => {
      this.userResponses[currentReasonKey] = (e.target as HTMLTextAreaElement).value;
    });

    // Prev Button
    document.getElementById('btn-prev-question')?.addEventListener('click', () => {
      if (index === 0) {
        this.currentScreen = 'user_info';
      } else if (index === 1) {
        this.currentScreen = 'dilemma_1';
      } else {
        this.currentScreen = 'dilemma_2';
      }
      this.render();
    });

    // Next / Finish Button
    document.getElementById('btn-next-question')?.addEventListener('click', async () => {
      if (!this.userResponses[currentChoiceKey]) {
        alert('보기를 선택해주세요.');
        return;
      }

      if (index < 2) {
        this.currentScreen = index === 0 ? 'dilemma_2' : 'dilemma_3';
        this.render();
      } else {
        // Last Question Submit
        const btnNext = document.getElementById('btn-next-question') as HTMLButtonElement;
        if (btnNext) {
          btnNext.disabled = true;
          btnNext.textContent = '통계 데이터 저장 중...';
        }

        const success = await this.submitUserResponses();
        if (success) {
          this.currentScreen = 'stats';
          this.render();
        }
      }
    });
  }

  private renderDilemmaScreenRebind(index: number) {
    // Soft re-render to update selected classes without destroying state
    const questionNum = index + 1;
    const choiceKey = `q${questionNum}_choice` as keyof UserResponses;
    const selected = this.userResponses[choiceKey];

    document.querySelectorAll('.option-btn').forEach(btn => {
      const choice = btn.getAttribute('data-choice');
      btn.className = `option-btn w-full p-4 sm:p-5 rounded-2xl text-left flex items-start space-x-3 cursor-pointer ${
        selected === 'A' && choice === 'A' ? 'selected-a' : selected === 'B' && choice === 'B' ? 'selected-b' : ''
      }`;
    });

    const reasonContainer = document.getElementById('reason-container');
    if (reasonContainer) {
      if (selected) {
        reasonContainer.classList.remove('hidden');
        reasonContainer.classList.add('animate-fade-in');
      }
    }

    const nextBtn = document.getElementById('btn-next-question') as HTMLButtonElement;
    if (nextBtn) {
      nextBtn.disabled = false;
      nextBtn.className = 'px-6 py-3 rounded-xl text-xs sm:text-sm font-bold text-white transition-all cursor-pointer bg-indigo-600 hover:bg-indigo-700 shadow-md shadow-indigo-200';
    }
  }

