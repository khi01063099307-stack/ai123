  private renderQualitativeReasons(responses: ResponseRecord[], qNum: number): string {
    const reasonKey = `q${qNum}_reason` as keyof ResponseRecord;
    const choiceKey = `q${qNum}_choice` as keyof ResponseRecord;

    const list = responses.filter(r => r[reasonKey] && (r[reasonKey] as string).trim() !== '');

    if (list.length === 0) {
      return `<p class="text-xs text-slate-400 italic py-2">등록된 서술형 이유가 아직 없습니다.</p>`;
    }

    return list.map(item => {
      const choice = item[choiceKey];
      const isA = choice === 'A';
      return `
        <div class="p-2.5 rounded-lg text-xs ${isA ? 'bg-indigo-50/60 border-l-3 border-l-indigo-500' : 'bg-sky-50/60 border-l-3 border-l-sky-500'} space-y-1">
          <div class="flex items-center justify-between text-[11px] font-semibold text-slate-500">
            <span class="${isA ? 'text-indigo-700 font-bold' : 'text-sky-700 font-bold'}">선택 [${choice}]</span>
            <span>${item.user_group} (${item.gender}, 만 ${item.age}세)</span>
          </div>
          <p class="text-slate-700 font-normal leading-relaxed">"${item[reasonKey]}"</p>
        </div>
      `;
    }).join('');
  }

